const db = require('../database/db');

class AIAdvisoryService {
    // Label stating advisory nature
    static ADVISORY_DISCLAIMER = 'ADVISORY NOTICE: This analysis is generated by the AICTE Digital Intelligence Engine as an advisory aid only. Under statutory regulations, this output does NOT constitute an approval, rejection, or statutory determination. Final verification by an authorised Council Officer is mandatory.';

    // Generate comprehensive executive case summary
    generateCaseSummary(applicationId) {
        const app = db.queryOne(`
            SELECT a.*, i.name as institution_name, i.permanent_id, i.state, i.institution_type, i.category,
                   i.establishment_year, r.name as region_name, at.name as type_name
            FROM applications a
            JOIN institutions i ON a.institution_id = i.id
            JOIN regions r ON a.assigned_region_id = r.id
            JOIN application_types at ON a.application_type_code = at.code
            WHERE a.id = ?
        `, [applicationId]);

        if (!app) throw new Error('Application not found.');

        const documents = db.query('SELECT * FROM documents WHERE application_id = ? OR institution_id = ?', [applicationId, app.institution_id]);
        const deficiencies = db.query('SELECT * FROM deficiencies WHERE application_id = ?', [applicationId]);
        const evcReports = db.query('SELECT * FROM evc_reports WHERE application_id = ?', [applicationId]);
        const transitions = db.query('SELECT * FROM stage_transitions WHERE application_id = ? ORDER BY timestamp ASC', [applicationId]);

        // Synthesize advisory insights
        const missingMandatoryDocs = documents.filter(d => d.current_status === 'EXPIRED' || d.current_status === 'REJECTED');
        const openDeficiencies = deficiencies.filter(d => d.status === 'RAISED' || d.status === 'DEFICIENT_PERSISTS');
        
        const summaryText = `Institution '${app.institution_name}' (${app.permanent_id}, ${app.institution_type}, ${app.category}) submitted an application for '${app.type_name}' for Academic Session ${app.academic_year}. The case is currently at stage '${app.current_stage}' with status '${app.current_status}'. Processing due date is ${app.processing_due_date.split('T')[0]}.`;

        const riskFlags = [];
        if (openDeficiencies.length > 0) {
            riskFlags.push(`${openDeficiencies.length} unresolved deficiencies exist requiring committee review.`);
        }
        if (missingMandatoryDocs.length > 0) {
            riskFlags.push(`${missingMandatoryDocs.length} required documents have expired or are invalid.`);
        }
        if (app.is_on_hold) {
            riskFlags.push(`Application is currently on administrative hold: "${app.hold_reason}".`);
        }

        return {
            disclaimer: AIAdvisoryService.ADVISORY_DISCLAIMER,
            applicationId,
            applicationNo: app.application_no,
            institutionName: app.institution_name,
            summary: summaryText,
            totalTransitionsCount: transitions.length,
            openDeficienciesCount: openDeficiencies.length,
            expiredDocumentsCount: missingMandatoryDocs.length,
            riskFlags,
            evcStatus: evcReports.length > 0 ? evcReports[0].overall_recommendation : 'Inspection Not Yet Finalised',
            suggestedOfficerAction: openDeficiencies.length > 0 ? 'Review Institution Clarification response' : 'Proceed with stage validation checklist'
        };
    }

    // Assist with standard deficiency wording based on regulatory clauses
    draftDeficiencyRecommendation(category, observation) {
        const standardClauses = {
            'Land & Building': {
                clause: 'APH-2026 Chapter I, Clause 2.4(a)',
                recommendation: 'The institution has not submitted registered lease deed for the requisite minimum land area of 2.5 acres in urban location, or lease period is less than 30 continuous years.'
            },
            'Faculty Cadre': {
                clause: 'AICTE Pay Scales & Cadre Ratio Reg. 2019, Cl 4.1',
                recommendation: 'Cadre ratio of Professor : Associate Professor : Assistant Professor (1:2:6) is deficient. Total faculty cadre deficiency exceeds allowable 10% tolerance.'
            },
            'Laboratory Equipment': {
                clause: 'APH-2026 Norms for Laboratories, Appendix 5',
                recommendation: 'Mandatory high-end specialized equipment for Core Computing and Simulation lab not physically demonstrated or verified during visual scrutiny.'
            },
            'Financial Reserve': {
                clause: 'APH-2026 Financial FDR Requirements, Appendix 8',
                recommendation: 'Joint Fixed Deposit Receipt (FDR) in favor of Regional Officer AICTE and Institution President has not been renewed or maturity proof is absent.'
            }
        };

        const matched = standardClauses[category] || {
            clause: 'APH-2026 General Norms',
            recommendation: `General deficiency observed: ${observation}`
        };

        return {
            disclaimer: AIAdvisoryService.ADVISORY_DISCLAIMER,
            category,
            regulatoryReference: matched.clause,
            suggestedDeficiencyDescription: matched.recommendation,
            suggestedAction: 'Require institution representative to upload attested documentary evidence within 7 working days.'
        };
    }
}

module.exports = new AIAdvisoryService();
